#!/usr/bin/env python3
"""Simple aggregation of per‑run NCCL CSV summaries.

This lightweight script reads a collection of CSV files generated by
`nccl_analysis_single.py` (or a compatible format) and computes median
bandwidth and timing values grouped by the columns that identify a unique
parameter set:

    Run Type, RDMA invoked, CPU cores per rank, Number of nodes, Message size (B)

It also adds a **Number of Replicates** column that records how many rows were
combined for each group.

Usage::

    python3 simple_aggregate.py <folder> [options]

Positional arguments:

    <folder>            Directory containing the per‑run CSV files.

Optional arguments:

    --glob PATTERN      Glob pattern for CSV files (default: "*.csv").
    --csv FILE          Path to write the aggregated CSV (default: "aggregated.csv").
    --output FILE       (Optional) Save an interactive Plotly HTML plot of median
                        out‑of‑place bus bandwidth vs. message size.
    --title TITLE       Title for the Plotly figure (defaults to a generated title).
"""

import argparse
import glob
import os
import pandas as pd
import plotly.express as px


def main():
    parser = argparse.ArgumentParser(
        description="Aggregate per‑run NCCL CSV summaries into median values.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("folder", help="Directory containing per‑run CSV files.")
    parser.add_argument(
        "--glob",
        type=str,
        default="*.csv",
        help="Glob pattern to match CSV files (default: *.csv).",
    )
    parser.add_argument(
        "--csv",
        type=str,
        default="aggregated.csv",
        help="Output path for the aggregated CSV.",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Optional path to save a Plotly HTML plot (out‑of‑place bus BW vs. size).",
    )
    parser.add_argument(
        "--title",
        type=str,
        default=None,
        help="Title for the Plotly figure (default constructed from folder name).",
    )
    parser.add_argument(
        "--devices-per-node",
        type=int,
        default=None,
        help="Number of devices per node (fills the 'Number of devices' column).",
    )
    args = parser.parse_args()

    # ---------------------------------------------------------------------
    # Discover CSV files
    # ---------------------------------------------------------------------
    csv_pattern = os.path.join(args.folder, args.glob)
    csv_files = glob.glob(csv_pattern)
    if not csv_files:
        print(f"[warning] No CSV files matched pattern {csv_pattern}")
        return
    print(f"[info] Found {len(csv_files)} per‑run CSV files.")

    # ---------------------------------------------------------------------
    # Load and concatenate
    # ---------------------------------------------------------------------
    dfs = [pd.read_csv(p) for p in csv_files]
    df = pd.concat(dfs, ignore_index=True)

    # ---------------------------------------------------------------------
    # Group and aggregate median values
    # ---------------------------------------------------------------------
    group_cols = [
        "Run Type",
        "System",
        "RDMA invoked",
        "CPU cores per rank",
        "Number of nodes",
        "Message size (B)",
    ]

    # Ensure the grouping columns exist (raise a clear error otherwise)
    missing = [c for c in group_cols if c not in df.columns]
    if missing:
        print(f"[error] Missing expected columns in input CSVs: {missing}")
        return

    # Compute median values for the performance columns
    median_agg = df.groupby(group_cols, as_index=False).agg(
        {
            "Median Out-of-Place Time (uS)": "median",
            "Median Out-of-Place Algorithmic Bandwidth (GB/s)": "median",
            "Median Out-of-Place Bus Bandwidth (GB/s)": "median",
            "Median In-Place Time (uS)": "median",
            "Median In-Place Algorithmic Bandwidth (GB/s)": "median",
            "Median In-Place Bus Bandwidth (GB/s)": "median",
        }
    )

    # Compute the number of replicates (rows) for each group
    count_agg = df.groupby(group_cols).size().reset_index(name="Number of Replicates")

    # Merge the median and count results
    agg = pd.merge(median_agg, count_agg, on=group_cols, how="left")

    # Fill the "Number of devices" column with the user‑provided value (or leave empty)
    agg["Number of devices"] = str(args.devices_per_node) if args.devices_per_node is not None else ""
    # Rename to match the requested column name
    agg.rename(columns={"Number of devices": "Number of devices per node"}, inplace=True)

    # Reorder columns to match the requested layout (including Number of Replicates at the end)
    output_order = [
        "Run Type",
        "System",
        "RDMA invoked",
        "CPU cores per rank",
        "Number of devices per node",
        "Number of nodes",
        "Message size (B)",
        "Median Out-of-Place Time (uS)",
        "Median Out-of-Place Algorithmic Bandwidth (GB/s)",
        "Median Out-of-Place Bus Bandwidth (GB/s)",
        "Median In-Place Time (uS)",
        "Median In-Place Algorithmic Bandwidth (GB/s)",
        "Median In-Place Bus Bandwidth (GB/s)",
        "Number of Replicates",
    ]
    # Keep only columns that exist (in case input CSVs lack any)
    agg = agg[[c for c in output_order if c in agg.columns]]

    # Write the result
    agg.to_csv(args.csv, index=False)
    print(f"[info] Aggregated CSV written to {args.csv}")

    # ---------------------------------------------------------------------
    # Optional Plotly visualisation (out‑of‑place bus bandwidth vs message size)
    # ---------------------------------------------------------------------
    if args.output:
        plot_df = agg.copy()
        # Define grouping columns for plotting
        group_cols = ["Run Type", "RDMA invoked", "CPU cores per rank", "Number of nodes"]
        missing_plot_cols = [c for c in group_cols if c not in plot_df.columns]
        if missing_plot_cols:
            print(f"[error] Missing expected columns for plotting: {missing_plot_cols}")
        else:
            # Create a combined column for grouping lines and legend entries with explicit labels
            plot_df["Plot Group"] = plot_df.apply(
                lambda r: f"Run Type={r['Run Type']}, RDMA invoked={r['RDMA invoked']}, CPU cores per rank={r['CPU cores per rank']}, Number of nodes={r['Number of nodes']}",
                axis=1,
            )
        fig = px.line(
            plot_df,
            x="Message size (B)",
            y="Median Out-of-Place Bus Bandwidth (GB/s)",
            color="Plot Group",
            markers=True,
            title=args.title or f"Median NCCL Out‑of‑Place Bus BW – {os.path.basename(args.folder)}",
            labels={"Plot Group": "Configuration"},
        )
        try:
            fig.write_html(args.output)
            print(f"[info] Plot saved to {args.output}")
        except Exception as e:
            print(f"[error] Could not save plot: {e}")


if __name__ == "__main__":
    main()
